#!/usr/bin/env bash
# Configure shared vs per-worktree Cargo target (see wisp-target.toml / Cargo.toml metadata).
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

usage() {
  sed -n '2,12p' "$0" | sed 's/^# \{0,1\}//'
  echo ""
  echo "Usage:"
  echo "  $0                 # ensure wisp-target.toml exists (shared default)"
  echo "  $0 --shared        # mode = shared"
  echo "  $0 --worktree      # mode = worktree (target/ in this checkout)"
  echo "  $0 --print         # print resolved CARGO_TARGET_DIR"
}

MODE=""
PRINT=0
while [[ $# -gt 0 ]]; do
  case "$1" in
    --shared)
      MODE=shared
      shift
      ;;
    --worktree)
      MODE=worktree
      shift
      ;;
    --print)
      PRINT=1
      shift
      ;;
    -h | --help)
      usage
      exit 0
      ;;
    *)
      echo "Unknown option: $1" >&2
      usage >&2
      exit 1
      ;;
  esac
done

if [[ -n "$MODE" ]]; then
  cat >"$ROOT/wisp-target.toml" <<EOF
# Generated by contrib/configure-dev-target.sh — edit freely (gitignored).
[build]
mode = "$MODE"
EOF
elif [[ ! -f "$ROOT/wisp-target.toml" ]]; then
  cp "$ROOT/wisp-target.example.toml" "$ROOT/wisp-target.toml"
  echo "Created wisp-target.toml (shared default). Edit or re-run with --worktree."
fi

TARGET="$(python3 "$ROOT/contrib/scripts/resolve-cargo-target-dir.py" "$ROOT")"
mkdir -p "$TARGET"

if [[ "$PRINT" -eq 1 ]]; then
  echo "$TARGET"
  exit 0
fi

mkdir -p "$ROOT/.vscode"
SETTINGS="$ROOT/.vscode/settings.json"
if [[ ! -f "$SETTINGS" ]]; then
  cat >"$SETTINGS" <<EOF
{
  "rust-analyzer.cargo.extraEnv": {
    "CARGO_TARGET_DIR": "$TARGET"
  }
}
EOF
  echo "Wrote $SETTINGS (CARGO_TARGET_DIR=$TARGET)"
else
  echo "Resolved CARGO_TARGET_DIR=$TARGET"
  echo "Add to rust-analyzer.cargo.extraEnv if the IDE does not source contrib/build-env.sh"
fi

echo "Shell: export CARGO_TARGET_DIR=\"$TARGET\""
echo "Or: source contrib/build-env.sh (hooks and ci-check already do)"
